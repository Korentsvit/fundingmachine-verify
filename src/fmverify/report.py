def _pct(value: Any) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        return 0.0
    return max(0.0, min(100.0, v))


def _bar(block: dict, keys: list[str], labels: dict) -> str:
    segments = "".join(
        f'<span class="k{i + 1}" style="width:{_pct(block.get("percent", {}).get(k)):.1f}%" title="{escape(labels[k])}: '
        f'{escape(str(block.get("percent", {}).get(k)))}%"></span>'
        for i, k in enumerate(keys)
    )
    return f'<div class="bar" role="img" aria-label="shares, as in the table below">{segments}</div>'


def _table(block: dict, keys: list[str], labels: dict) -> str:
    rows = "".join(
        f'<tr><td><span class="swatch k{i + 1}"></span>{escape(labels[k])}</td>'
        f'<td class="num">{escape(str(block.get("counts", {}).get(k, "")))}</td>'
        f'<td class="num">{escape(str(block.get("percent", {}).get(k, "")))}%</td></tr>'
        for i, k in enumerate(keys)
    )
    return (f'<table><thead><tr><th>Origin</th><th class="num">Characters</th><th class="num">Share</th></tr></thead>'
            f'<tbody>{rows}<tr><th>Total</th><td class="num">{escape(str(block.get("total", "")))}</td><td></td></tr></tbody></table>')


def _checks(verdict: Verdict) -> str:
    rows = []
    for c in verdict.checks:
        reasons = "".join(f"<li>{escape(r)}</li>" for r in c.reasons)
        optional = "" if c.required else ' <span class="muted">(optional)</span>'
        rows.append(f'<tr><td class="{c.status.value}">{escape(c.status.value.replace("_", " "))}</td>'
                    f'<td class="mono">{escape(c.id)}{optional}</td><td>{escape(c.summary)}'
                    f'{"<ul>" + reasons + "</ul>" if reasons else ""}</td></tr>')
    return f'<table><thead><tr><th>Status</th><th>Check</th><th>Finding</th></tr></thead><tbody>{"".join(rows)}</tbody></table>'


def _certificate_sections(verdict: Verdict, cred: dict) -> str:
    subj = cred.get("credentialSubject") or {}
    status = {c.id: c.status for c in verdict.checks}
    recomputed = status.get("certificate.authorship_map") is Status.PASS
    provenance = ("Recomputed by this verifier from the event chain: the figures match the signed certificate."
                  if recomputed else
                  "As stated in the signed certificate. The event chain was not given, so these figures were not recomputed.")
    if verdict.outcome is Outcome.INVALID:
        provenance = "The certificate did not verify: the figures below are its claims and must not be relied on."
    out = []
    scope = subj.get("scope_statement")
    if scope:
        out.append(f'<div class="scope"><strong>Scope, as the certificate states it:</strong> {escape(scope)}</div>')
    doc = subj.get("document") or {}
    signed = subj.get("signed") or {}
    file_state = {Status.PASS: "presented, and it matches", Status.FAIL: "presented, and it does not match"}.get(
        status.get("certificate.file"), "not presented")
    out.append("<h2>Document</h2><table><tbody>"
               f'<tr><th>Document id</th><td class="mono">{escape(str(subj.get("doc_id")))}</td></tr>'
               f'<tr><th>Exported file</th><td><span class="mono">{escape(str(doc.get("exported_sha256")))}</span> '
               f'({escape(str(doc.get("media_type")))}, {escape(str(doc.get("byte_length")))} bytes); {file_state}</td></tr>'
               f'<tr><th>Signed</th><td>event {escape(str(signed.get("seq")))} at {escape(str(signed.get("ts")))} by '
               f'<span class="mono">{escape(str(signed.get("actor_id")))}</span> (a pseudonymous id)</td></tr>'
               f'<tr><th>Issuer</th><td class="mono">{escape(str((cred.get("issuer") or {}).get("id")))}</td></tr>'
               "</tbody></table>")
    a = subj.get("authorship") or {}
    origins = list(ORIGIN_LABELS)
    fidelities = list(FIDELITY_LABELS)
    out.append(f'<h2>Authorship map</h2><p class="note">{escape(provenance)} The map shows which event in this environment put '
               "each character where it is. Imported text may have been written anywhere; the map cannot say where.</p>")
    if a.get("document"):
        out.append("<h3>Whole document</h3>" + _bar(a["document"], origins, ORIGIN_LABELS) + _table(a["document"], origins, ORIGIN_LABELS))
    for s in a.get("sections") or []:
        ref = f' <span class="mono muted">{escape(s["section_ref"])}</span>' if s.get("section_ref") else ""
        out.append(f'<h3>Section {escape(str(s.get("section_id")))}{ref}</h3>'
                   f'<p class="note">{escape(str(s.get("statements")))} statement{"" if s.get("statements") == 1 else "s"}</p>'
                   + _bar(s, origins, ORIGIN_LABELS) + _table(s, origins, ORIGIN_LABELS))
    if a.get("fidelity"):
        out.append('<h3>How the characters were observed</h3>' + _bar(a["fidelity"], fidelities, FIDELITY_LABELS)
                   + _table(a["fidelity"], fidelities, FIDELITY_LABELS).replace("<th>Origin</th>", "<th>Fidelity</th>"))
    act = a.get("activity") or {}
    if act:
        ins = "".join(f'<tr><td>{escape(ORIGIN_LABELS[k])}</td><td class="num">{escape(str(act.get("inserted", {}).get(k, "")))}</td></tr>'
                      for k in origins)
        out.append(f'<h3>Activity</h3><table><thead><tr><th>Characters ever inserted</th><th class="num">Count</th></tr></thead>'
                   f'<tbody>{ins}<tr><th>Characters ever deleted</th><td class="num">{escape(str(act.get("deleted", "")))}</td></tr></tbody></table>')
    ev = subj.get("evidence") or {}
    n, w = ev.get("statements"), ev.get("statements_with_evidence")
    coverage = f"{w} of {n} statements" if isinstance(n, int) and isinstance(w, int) else "not stated"
    rows = "".join(
        f'<tr><td class="mono">{escape(str(b.get("statement_id")))}</td><td class="mono">{escape(str((b.get("source") or {}).get("ref")))}</td>'
        f'<td>{escape(str((b.get("date") or {}).get("kind")))} {escape(str((b.get("date") or {}).get("value")))}</td>'
        f'<td>{escape(str(b.get("licence")))}</td><td>{escape(str((b.get("quoted_span") or {}).get("locator") or ""))}</td>'
        f'<td class="mono">{escape(str(b.get("page_hash")))}</td></tr>'
        for b in ev.get("bindings") or [])
    out.append(f'<h2>Evidence coverage</h2><p>Statements bound to a source: <strong>{escape(coverage)}</strong>.</p>'
               + (f'<table><thead><tr><th>Statement</th><th>Source</th><th>Date</th><th>Licence</th><th>Where</th><th>Page hash</th></tr></thead>'
                  f'<tbody>{rows}</tbody></table>' if rows else '<p class="note">No active bindings.</p>'))
    tools = subj.get("tools") or []
    tool_rows = "".join(f'<li>{escape(str(t.get("tool_name")))} <span class="muted">model: {escape(str(t.get("model_id") or "not reported"))}</span></li>'
                        for t in tools)
    out.append(f'<h2>Tools that wrote in this document</h2>{"<ul>" + tool_rows + "</ul>" if tool_rows else "<p>None recorded.</p>"}')
    return "".join(out)


def render(verdict: Verdict, certificate: dict | None = None, title: str | None = None) -> str:
    """The verdict as a self-contained HTML page; with the certificate's JSON,
    its authorship map and evidence coverage as well."""
    outcome = verdict.outcome.value
    body = [
        f"<h1>{escape(title or 'Verification report')}</h1>",
        f'<p class="muted">{escape(verdict.subject)}</p>',
        f'<div class="outcome {outcome}"><span class="badge">{escape(outcome.upper())}</span><p>{escape(verdict.statement)}</p></div>',
    ]
    if certificate is not None:
        body.append(_certificate_sections(verdict, certificate))
    body.append("<h2>Checks</h2>" + _checks(verdict))
    if verdict.relies_on:
        body.append("<h2>What this relies on</h2><ul>" + "".join(f"<li>{escape(r)}</li>" for r in verdict.relies_on) + "</ul>")
    if verdict.does_not_establish:
        body.append("<h2>What this does not establish</h2><ul>"
                    + "".join(f"<li>{escape(r)}</li>" for r in verdict.does_not_establish) + "</ul>")
    body.append(f'<p class="note">{escape(verdict.tool["name"])} {escape(verdict.tool["version"])}, checked at {escape(verdict.checked_at)}. '
                "This page is a rendering of the verdict; the command-line verifier is the proof.</p>")
    page_title = escape(title or f"Verification report: {outcome}")
    return ("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
            f"<title>{page_title}</title><style>{CSS}</style></head><body><main>{''.join(body)}</main></body></html>\n")
