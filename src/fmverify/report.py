"""Static HTML reports: a verdict, and for a certificate its authorship map and
evidence coverage, on one self-contained page.

No script, no external stylesheet, font or image: the page shows the same on
any machine and keeps nothing hidden. Every figure from a certificate is
labelled with whether the verifier recomputed it from the event chain or only
read it from the signed certificate. The certificate's own scope statement is
printed near the top, word for word.
"""

from __future__ import annotations

from html import escape
from typing import Any

from .verdict import Outcome, Status, Verdict

ORIGIN_LABELS = {
    "human_typed": "Typed by a person in this environment",
    "imported": "Imported (pasted, or present when capture began)",
    "tool_generated": "Generated by a tool",
    "tool_edited": "Edited by a tool",
}
FIDELITY_LABELS = {
    "live": "Observed live",
    "snapshot_diff": "Inferred from snapshots",
    "tool_report": "Reported by the tool",
    "reconstructed": "Reconstructed afterwards",
    "declared": "Declared by a person",
}

