"""Hash functions the proof formats name, with pure-Python fallbacks.

SHA-1 and SHA-256 come from hashlib. RIPEMD-160 comes from hashlib when the
local OpenSSL still provides it (OpenSSL 3 moved it to the legacy provider),
otherwise from the implementation below. Keccak-256 (the original Keccak
padding, as Ethereum uses it, not SHA3-256) is always the implementation below.
Both are checked against published test vectors in the test suite.
"""

from __future__ import annotations

import hashlib
import struct

_M32 = 0xFFFFFFFF
_M64 = 0xFFFFFFFFFFFFFFFF


def sha256(data: bytes) -> bytes:
    return hashlib.sha256(data).digest()


def sha256d(data: bytes) -> bytes:
    return hashlib.sha256(hashlib.sha256(data).digest()).digest()


def sha1(data: bytes) -> bytes:
    return hashlib.sha1(data).digest()


