def _rol32(x: int, n: int) -> int:
    return ((x << n) | (x >> (32 - n))) & _M32


def _f(j: int, x: int, y: int, z: int) -> int:
    if j < 16:
        return x ^ y ^ z
    if j < 32:
        return (x & y) | (~x & z)
    if j < 48:
        return (x | ~y) ^ z
    if j < 64:
        return (x & z) | (y & ~z)
    return x ^ (y | ~z)


def ripemd160_pure(data: bytes) -> bytes:
    h = [0x67452301, 0xEFCDAB89, 0x98BADCFE, 0x10325476, 0xC3D2E1F0]
    padded = data + b"\x80" + b"\x00" * ((55 - len(data)) % 64) + struct.pack("<Q", (8 * len(data)) & _M64)
    for off in range(0, len(padded), 64):
        x = struct.unpack("<16I", padded[off : off + 64])
        al, bl, cl, dl, el = h
        ar, br, cr, dr, er = h
        for j in range(80):
            t = _rol32((al + _f(j, bl, cl, dl) + x[_RL[j]] + _KL[j // 16]) & _M32, _SL[j])
            t = (t + el) & _M32
            al, el, dl, cl, bl = el, dl, _rol32(cl, 10), bl, t
            t = _rol32((ar + _f(79 - j, br, cr, dr) + x[_RR[j]] + _KR[j // 16]) & _M32, _SR[j])
            t = (t + er) & _M32
            ar, er, dr, cr, br = er, dr, _rol32(cr, 10), br, t
        t = (h[1] + cl + dr) & _M32
        h[1] = (h[2] + dl + er) & _M32
        h[2] = (h[3] + el + ar) & _M32
        h[3] = (h[4] + al + br) & _M32
        h[4] = (h[0] + bl + cr) & _M32
        h[0] = t
    return struct.pack("<5I", *h)


def ripemd160(data: bytes) -> bytes:
    try:
        return hashlib.new("ripemd160", data).digest()
    except (ValueError, TypeError):
        return ripemd160_pure(data)


